/** 시흥시 범위. 핀·검색은 경계선 안(바닷가는 [COAST_TOLERANCE_M] 여유)만 받는다. */
internal object SiheungArea {
    // 경계선을 둘러싼 네모 (검색 범위용)
    val NORTH = SIHEUNG_BOUNDARY.maxOf { it.first }
    val SOUTH = SIHEUNG_BOUNDARY.minOf { it.first }
    val WEST = SIHEUNG_BOUNDARY.minOf { it.second }
    val EAST = SIHEUNG_BOUNDARY.maxOf { it.second }

    /** 좌표가 없을 때 보여줄 곳 (시흥 한가운데쯤) */
    const val CENTER_LAT = 37.3800
    const val CENTER_LNG = 126.7840

    /** 등대·방파제·해안처럼 경계선 바로 바깥도 시흥으로 쳐주는 여유 (m) */
    const val COAST_TOLERANCE_M = 500.0

    fun contains(lat: Double, lng: Double): Boolean =
        insidePolygon(lat, lng) || distanceToBorderMeters(lat, lng) <= COAST_TOLERANCE_M

    /** 점이 다각형 안에 있는지 (반직선 교차 개수) */
    private fun insidePolygon(lat: Double, lng: Double): Boolean {
        var inside = false
        var j = SIHEUNG_BOUNDARY.lastIndex
        for (i in SIHEUNG_BOUNDARY.indices) {
            val (yi, xi) = SIHEUNG_BOUNDARY[i]
            val (yj, xj) = SIHEUNG_BOUNDARY[j]
            if ((yi > lat) != (yj > lat) && lng < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside
            j = i
        }
        return inside
    }

    /** 경계선까지 가장 가까운 거리 (m, 좁은 지역이라 평면 근사) */
    private fun distanceToBorderMeters(lat: Double, lng: Double): Double {
        val mPerLat = 111_320.0
        val mPerLng = 111_320.0 * cos(Math.toRadians(lat))
        var best = Double.MAX_VALUE
        var j = SIHEUNG_BOUNDARY.lastIndex
        for (i in SIHEUNG_BOUNDARY.indices) {
            val ax = (SIHEUNG_BOUNDARY[j].second - lng) * mPerLng
            val ay = (SIHEUNG_BOUNDARY[j].first - lat) * mPerLat
            val bx = (SIHEUNG_BOUNDARY[i].second - lng) * mPerLng
            val by = (SIHEUNG_BOUNDARY[i].first - lat) * mPerLat
            val dx = bx - ax
            val dy = by - ay
            val len2 = dx * dx + dy * dy
            val t = if (len2 == 0.0) 0.0 else (-(ax * dx + ay * dy) / len2).coerceIn(0.0, 1.0)
            val px = ax + t * dx
            val py = ay + t * dy
            best = minOf(best, sqrt(px * px + py * py))
            j = i
        }
        return best
    }
}
